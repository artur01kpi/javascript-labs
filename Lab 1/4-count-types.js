// Створюємо функцію countTypes, яка приймає один масив (називаємо його list)
const countTypes = (list) => {
  // Створюємо порожній об'єкт-колекцію (хеш), куди будемо записувати результати підрахунку
  const counters = {};

  // Запускаємо цикл for..of, який по черзі бере кожен елемент (item) з нашого масиву
  for (const item of list) {
    // За допомогою оператора typeof дізнаємося тип поточного елемента (наприклад: 'number', 'string', 'boolean')
    const type = typeof item;

    // Перевіряємо: якщо ми ТАКЙ ТИП ще не зустрічали в нашому об'єкті counters,
    // то створюємо для нього нову комірку і ставимо початкове значення 0
    if (!counters[type]) {
      counters[type] = 0;
    }

    // Збільшуємо лічильник для цього типу даних на одиницю
    counters[type] = counters[type] + 1;
  }

  // Після того, як цикл закінчився, повертаємо наш готовий об'єкт із підрахунками
  return counters;
};

// Експортуємо функцію, щоб було видно
module.exports = { countTypes };


// --- ПЕРЕВІРКА ---
// Створюємо тестовий масив із різними типами даних, як просили в умові
const testArray = [true, 'hello', 5, 12, -200, false, false, 'word', 'js', 42];

// Запускаємо нашу функцію для цього масиву та записуємо результат
const result = countTypes(testArray);

// Виводимо масив і фінальний об'єкт-лічильник на екран
console.log('Початковий масив:', testArray);
console.log('Результат підрахунку типів:', result);
