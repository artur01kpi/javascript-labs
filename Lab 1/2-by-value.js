// Наша функція, яку ми написали
const inc = (n) => {
  return n + 1;
};

// Експорт для майбутньої задачі
module.exports = { inc };

// --- ПЕРЕВІРКА З ВВОДОМ У ТЕРМІНАЛІ ---

// 1. Підключаємо модуль Node.js для роботи з терміналом
const readline = require('readline');

// 2. Налаштовуємо введення/виведення
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

// 3. Запитуємо число у користувача
rl.question('Введіть будь-яке число: ', (input) => {
  // Перетворюємо введений текст на справжнє число
  const a = Number(input); 
  
  // Викликаємо нашу функцію, передаємо туди введене число і записуємо результат у "b"
  const b = inc(a); 

  // Виводимо в консоль обидва значення, щоб подивитися, що вийшло
  console.log('Початкове число a =', a);
  console.log('Результат після функції b =', b);

  // Закриваємо інтерфейс терміналу, щоб програма зупинилася
  rl.close();
});
