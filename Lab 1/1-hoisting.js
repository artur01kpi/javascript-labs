// Оголошуємо функцію з назвою hoisting, як цього вимагає завдання
const hoisting = () => {
  
  // Виводимо значення змінної у консоль ДО того, як ми її оголосили нижче.
  // Оскільки ми використовуємо старе слово 'var', JavaScript "підніме" саму змінну,
  // але не її значення. Тому на цьому етапі на екрані з'явиться: undefined
  console.log('Значення змінної перед оголошенням:', message);

  // Оголошуємо змінну через var та присвоюємо їй текстове значення.
  // Саме через ключове слово var відбувається ефект hoisting (підняття)
  var message = 'Привіт! Ця змінна зазнала підняття.';

  // Виводимо змінну ще раз, але вже ПІСЛЯ того, як присвоїли значення.
  // Тепер на екрані ми побачимо нормальний текст
  console.log('Значення змінної після оголошення:', message);
};
// Ми експортуємо нашу функцію назовні.
module.exports = { hoisting };
hoisting()
