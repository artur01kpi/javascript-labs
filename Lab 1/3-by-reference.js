// Наша функція, яка приймає об'єкт
const inc = (obj) => {
  // Змінюємо поле "n" оригінального об'єкта прямо всередині
  obj.n = obj.n + 1;
};

// Експортуємо функцію
module.exports = { inc };

// --- ПЕРЕВІРКА З ВВОДОМ У ТЕРМІНАЛІ ---

// 1. Підключаємо модуль для роботи з терміналом
const readline = require('readline');

// 2. Налаштовуємо введення/виведення
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

// 3. Запитуємо початкове значення для об'єкта
rl.question('Введіть початкове число для об\'єкта: ', (input) => {
  // Перетворюємо введений текст на число
  const userNumber = Number(input);

  // Створюємо об'єкт і кладемо введене число у властивість "n"
  const myObj = { n: userNumber };

  // Виводимо об'єкт ДО запуску функції
  console.log('Об\'єкт ДО функції:', myObj);

  // Передаємо наш об'єкт у функцію. Вона змінить значення прямо в ньому!
  inc(myObj);

  // Виводимо той самий об'єкт ПІСЛЯ функції, щоб побачити зміни
  console.log('Об\'єкт ПІСЛЯ функції:', myObj);

  // Закриваємо термінал
  rl.close();
});
