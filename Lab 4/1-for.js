'use strict';

const sum = (...args) => {
  let total = 0; // Створюємо змінну для накопичення суми

  // Класичний цикл for з лічильником i
  for (let i = 0; i < args.length; i++) {
    total += args[i]; // Додаємо поточне число до загальної суми
  }

  return total; // Повертаємо фінальний результат
};

module.exports = { sum }; // Експортуємо функцію 


// --- ПЕРЕВІРКА КОДУ (можеш видалити перед здачею) ---
console.log(sum(1, 2, 3));    // Має вивести: 6
console.log(sum(10, -2, 5));  // Має вивести: 13
console.log(sum());           // Має вивести: 0 (якщо нічого не передали)
