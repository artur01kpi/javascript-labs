// Підключаємо вбудований модуль Node.js для зчитування з консолі
const readline = require('readline');

// Створюємо інтерфейс введення-виведення з клавіатури та в термінал
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

// --- 1. Допоміжні математичні функції ---

// Обчислення середнього арифметичного двох чисел
const average = (a, b) => (a + b) / 2;

// Обчислення квадрата числа (множення на самого себе)
const square = (x) => x * x;

// Обчислення куба числа (множення тричі)
const cube = (x) => x * x * x;


// --- 2. Головна функція обчислень за умовою лабораторної ---

// Функція обчислює середнє арифметичне квадратів і кубів від 0 до заданого числа (end)
const calculate = (end = 9) => {
  const results = []; // Створюємо порожній масив для збору результатів
  
  for (let i = 0; i <= end; i++) { // Цикл від 0 до вказаного числа включно
    const sq = square(i);          // Викликаємо функцію для квадрата поточного числа
    const cb = cube(i);            // Викликаємо функцію для куба поточного числа
    const avg = average(sq, cb);   // Рахуємо середнє арифметичне отриманих квадрата і куба
    
    results.push(avg);             // Записуємо результат обчислення в масив
  }
  
  return results; // Повертаємо готовий масив із результатами
};


// --- 3. Логіка взаємодії з користувачем через термінал ---

// Запитуємо у користувача кінцеве число для розрахунків
rl.question('Введи будь-яке число для обчислень (наприклад, 9): ', (userInput) => {
  
  // Перетворюємо введені текстові дані на справжнє ціле число
  const maxNumber = parseInt(userInput, 10);

  // Перевіряємо, чи користувач ввів саме число і чи воно не менше нуля
  if (!isNaN(maxNumber) && maxNumber >= 0) {
    console.log('\n--- Результати обчислень ---');
    console.log(`Квадрат твого числа (${maxNumber}):`, square(maxNumber));
    console.log(`Куб твого числа (${maxNumber}):`, cube(maxNumber));
    
    console.log(`\nМасив середніх значень (від 0 до ${maxNumber}):`);
    console.log(calculate(maxNumber));
  } else {
    // Попередження на випадок помилки введення
    console.log('Помилка! Будь ласка, введи коректне додатне число.');
  }

  // Закриваємо інтерфейс введення, щоб програма успішно завершила роботу
  rl.close();
});

// Експортуємо функції, щоб оригінальні тести курсу працювали без змін
module.exports = { average, square, cube, calculate };
