// Підключаємо вбудований модуль Node.js для зчитування з консолі
const readline = require('readline');

// Створюємо інтерфейс введення-виведення з клавіатури та в термінал
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

// --- 1. функції обчислень ---

// Функція range: приймає початок і кінець, повертає масив усіх чисел між ними
const range = (start, end) => {
  const arr = []; // Створюємо порожній масив
  for (let i = start; i <= end; i++) { // Цикл від start до end включно
    arr.push(i); // Додаємо кожне число в масив
  }
  return arr; // Повертаємо готовий масив чисел
};

// Функція rangeOdd: робить те саме, але повертає масив тільки НЕПАРНИХ чисел
const rangeOdd = (start, end) => {
  const arr = []; // Створюємо порожній масив
  for (let i = start; i <= end; i++) { // Цикл від start до end включно
    if (i % 2 !== 0) { // Перевірка: якщо залишок від ділення на 2 не дорівнює 0 (непарне)
      arr.push(i); // Додаємо тільки непарне число в масив
    }
  }
  return arr; // Повертаємо готовий масив непарних чисел
};

// --- 2. Логіка взаємодії з користувачем через термінал ---

// Запитуємо у користувача перше число
rl.question('Введи перше число (початок): ', (num1) => {
  // Запитуємо у користувача друге число
  rl.question('Введи друге число (кінець): ', (num2) => {
    
    // Перетворюємо введені текстові рядки на справжні цілі числа
    const start = parseInt(num1, 10);
    const end = parseInt(num2, 10);

    // Перевіряємо, чи користувач ввів коректні числа (а не літери)
    if (!isNaN(start) && !isNaN(end)) {
      console.log('\n--- Результати ---');
      // Викликаємо функції та виводимо результати їх роботи на екран
      console.log('Повний масив чисел (range):', range(start, end));
      console.log('Масив непарних чисел (rangeOdd):', rangeOdd(start, end));
    } else {
      // Якщо ввели текст замість чисел, виводимо попередження
      console.log('Помилка! Будь ласка, вводь тільки числа.');
    }

    // Обов'язково закриваємо інтерфейс введення, щоб програма завершила роботу
    rl.close();
  });
});

// Експортуємо чисті функції для автоматичних тестів курсу
module.exports = { range, rangeOdd };
